function make(theme) {
  let art=frame(theme);
  if(theme==='frost') art+=frostRifts()+ice();
  if(theme==='blaze') art+=fire();
  if(theme==='volt') art+=city();
  if(theme==='silvah') art+=lightning()+lion();
  art+=portrait(theme)+foreground(theme)+particles(theme);
  return div(`r2-art r2-energy r2-energy-css ${theme}`,art);
}

