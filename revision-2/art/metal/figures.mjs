function commands(d) {
  const tokens=d.match(/[MLCQZ]|-?(?:\d*\.)?\d+(?:e[-+]?\d+)?/gi),out=[];
  const sizes={M:2,L:2,C:6,Q:4,Z:0};
  for(let i=0;i<tokens.length;){const c=tokens[i++].toUpperCase(),n=sizes[c];if(n===undefined)throw Error(`Unsupported contour ${c}`);out.push([c,...tokens.slice(i,i+n).map(Number)]);i+=n;}
  return out;
}
function flatten(cmds) {
  const paths=[];let a=[],last=[0,0],start=[0,0];
  for(const [c,...v] of cmds){
    if(c==='M'){if(a.length)paths.push(a);a=[[v[0],v[1]]];last=start=[v[0],v[1]];}
    if(c==='L'){a.push(v);last=v;}
    if(c==='C'||c==='Q'){
      const end=v.slice(-2),control=v.slice(0,-2),points=[last,...Array.from({length:control.length/2},(_,i)=>control.slice(i*2,i*2+2)),end];
      const len=points.slice(1).reduce((s,p,i)=>s+Math.hypot(p[0]-points[i][0],p[1]-points[i][1]),0),steps=Math.min(28,Math.max(4,Math.ceil(len/3)));
      const p=last;
      for(let i=1;i<=steps;i++){const t=i/steps,u=1-t;a.push(c==='C'?[u*u*u*p[0]+3*u*u*t*v[0]+3*u*t*t*v[2]+t*t*t*v[4],u*u*u*p[1]+3*u*u*t*v[1]+3*u*t*t*v[3]+t*t*t*v[5]]:[u*u*p[0]+2*u*t*v[0]+t*t*v[2],u*u*p[1]+2*u*t*v[1]+t*t*v[3]]);}
      last=end;
    }
    if(c==='Z'){a.push(start);last=start;}
  }
  if(a.length)paths.push(a);return paths;
}
function outline(points,width) {
  const left=[],right=[];
  points.forEach((p,i)=>{const a=points[Math.max(0,i-1)],b=points[Math.min(points.length-1,i+1)],dx=b[0]-a[0],dy=b[1]-a[1],l=Math.hypot(dx,dy)||1,nx=-dy/l*width/2,ny=dx/l*width/2;left.push([p[0]+nx,p[1]+ny]);right.push([p[0]-nx,p[1]-ny]);});
  return [...left,...right.reverse()];
}
function cssPaint(p) {
  if(typeof p==='string')return p;
  const stops=p.stops.map(([s,c])=>`${c} ${num(s*100)}%`).join(',');
  return p.type==='radial'?`radial-gradient(ellipse at ${p.x*100}% ${p.y*100}%,${stops})`:`linear-gradient(${p.angle}deg,${stops})`;
}
function bounds(paths) {
  const points=paths.flat();const xs=points.map(p=>p[0]),ys=points.map(p=>p[1]);
  const x=Math.floor(Math.min(...xs)*100)/100,y=Math.floor(Math.min(...ys)*100)/100;
  return [x,y,Math.max(.1,Math.ceil((Math.max(...xs)-x)*100)/100),Math.max(.1,Math.ceil((Math.max(...ys)-y)*100)/100)];
}
