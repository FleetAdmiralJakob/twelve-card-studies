  let d=top.map(([a,b],i)=>`${i?'L':'M'}${n(x+a*w)} ${n(y+b*h)}`).join('');
  d+=`C${x+w*.69} ${y+h*.65} ${x+w*.47} ${y+h*.59} ${x+w*.28} ${y+h*.76}L${x+w*.14} ${y+h}L${x+w*.06} ${y+h*.8}Z`;
